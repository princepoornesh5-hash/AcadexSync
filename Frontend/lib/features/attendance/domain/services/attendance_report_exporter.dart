/// Service responsible for generating standardized CSV and structured printable reports
/// from Attendance domain and analytics models.
class AttendanceReportExporter {
  AttendanceReportExporter._();

  /// Escapes a single CSV value according to RFC 4180.
  /// Handles quotes, commas, CRLF, empty strings, and Unicode characters safely.
  static String escapeCsv(dynamic value) {
    if (value == null) return '';
    final str = value.toString();
    if (str.contains(',') || str.contains('"') || str.contains('\n') || str.contains('\r')) {
      return '"${str.replaceAll('"', '""')}"';
    }
    return str;
  }

  /// Formats a list of values as a standard CSV row
  static String formatRow(List<dynamic> values) {
    return values.map(escapeCsv).join(',');
  }

  /// Formats date range label
  static String formatDateRange(AttendanceDateRange? dateRange) {
    if (dateRange == null) return 'All Time';
    return '${dateRange.startDate.toIso8601String().split('T').first} to ${dateRange.endDate.toIso8601String().split('T').first}';
  }

  /// Converts an AttendanceReportResult into a deterministic CSV string
  static String generateReportCsv(AttendanceReportResult report) {
    final buffer = StringBuffer();

    // Institutional Header
    buffer.writeln(formatRow(['ACADEX ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['Report Title', report.title]));
    buffer.writeln(formatRow(['Scope', report.scopeDescription]));
    buffer.writeln(formatRow(['Generated At', report.generatedAt.toIso8601String()]));
    buffer.writeln(formatRow(['Generated By', report.generatedBy]));
    if (report.dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(report.dateRange)]));
    }
    buffer.writeln(formatRow(['Total Records', report.totalRecords]));

    // Summary Statistics
    if (report.summaryStatistics.isNotEmpty) {
      buffer.writeln();
      buffer.writeln(formatRow(['--- SUMMARY STATISTICS ---']));
      for (final entry in report.summaryStatistics.entries) {
        buffer.writeln(formatRow([entry.key, entry.value]));
      }
    }

    buffer.writeln();

    // Data Table Headers
    buffer.writeln(formatRow(report.headers));

    // Data Table Rows
    if (report.rows.isEmpty) {
      buffer.writeln(formatRow(List.filled(report.headers.length, 'No records found')));
    } else {
      for (final row in report.rows) {
        buffer.writeln(formatRow(row));
      }
    }

    return buffer.toString();
  }

  /// Generates CSV report for a single student's attendance & subject breakdown
  static String generateStudentAttendanceCsv({
    required StudentAttendanceAnalytics student,
    List<SubjectAttendanceAnalytics> subjects = const [],
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();

    buffer.writeln(formatRow(['ACADEX STUDENT ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['Student Name', student.studentName]));
    buffer.writeln(formatRow(['Roll Number', student.rollNumber]));
    buffer.writeln(formatRow(['Section', student.sectionId]));
    buffer.writeln(formatRow(['Overall Attendance', '${student.attendancePercentage.toStringAsFixed(1)}%']));
    buffer.writeln(formatRow(['Risk Standing', student.riskLevel.name.toUpperCase()]));
    buffer.writeln(formatRow(['Total Sessions', student.totalSessions]));
    buffer.writeln(formatRow(['Present', student.presentCount]));
    buffer.writeln(formatRow(['Absent', student.absentCount]));
    buffer.writeln(formatRow(['Late', student.lateCount]));
    buffer.writeln(formatRow(['Excused', student.excusedCount]));
    if (student.isLowAttendance) {
      buffer.writeln(formatRow(['Sessions Needed for 75%', student.recoverySessionsNeeded]));
    }
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Subject Name',
      'Subject Code',
      'Total Classes',
      'Attendance %',
      'Present',
      'Absent',
      'Late',
      'Excused',
      'Risk Level',
    ]));

    if (subjects.isEmpty) {
      buffer.writeln(formatRow(['No individual subject records available', '', '', '', '', '', '', '', '']));
    } else {
      for (final sub in subjects) {
        buffer.writeln(formatRow([
          sub.subjectName.isNotEmpty ? sub.subjectName : sub.subjectId,
          sub.subjectId,
          sub.totalSessions,
          '${sub.attendancePercentage.toStringAsFixed(1)}%',
          sub.presentCount,
          sub.absentCount,
          sub.lateCount,
          sub.excusedCount,
          sub.riskLevel.name.toUpperCase(),
        ]));
      }
    }

    return buffer.toString();
  }

  /// Generates CSV report for a section and its student roster ranking
  static String generateSectionAttendanceCsv({
    required SectionAttendanceAnalytics section,
    List<StudentAttendanceAnalytics>? studentsOverride,
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();
    final effectiveStudents = studentsOverride ?? section.studentAnalytics;

    buffer.writeln(formatRow(['ACADEX SECTION ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['Section Name', section.sectionName.isNotEmpty ? section.sectionName : section.sectionId]));
    buffer.writeln(formatRow(['Overall Attendance', '${section.attendancePercentage.toStringAsFixed(1)}%']));
    buffer.writeln(formatRow(['Total Students', section.totalStudents]));
    buffer.writeln(formatRow(['Total Sessions', section.totalSessions]));
    buffer.writeln(formatRow(['Students Below 75%', section.lowAttendanceStudentCount]));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Rank',
      'Student Name',
      'Roll Number',
      'Attendance %',
      'Risk Level',
      'Total Sessions',
      'Present',
      'Absent',
      'Late',
      'Excused',
      'Recovery Needed (75%)',
    ]));

    if (effectiveStudents.isEmpty) {
      buffer.writeln(formatRow(['No student records found in section', '', '', '', '', '', '', '', '', '', '']));
    } else {
      final sorted = List<StudentAttendanceAnalytics>.from(effectiveStudents)
        ..sort((a, b) => b.attendancePercentage.compareTo(a.attendancePercentage));

      for (int i = 0; i < sorted.length; i++) {
        final s = sorted[i];
        buffer.writeln(formatRow([
          i + 1,
          s.studentName.isNotEmpty ? s.studentName : s.studentId,
          s.rollNumber,
          '${s.attendancePercentage.toStringAsFixed(1)}%',
          s.riskLevel.name.toUpperCase(),
          s.totalSessions,
          s.presentCount,
          s.absentCount,
          s.lateCount,
          s.excusedCount,
          s.isLowAttendance ? s.recoverySessionsNeeded : 0,
        ]));
      }
    }

    return buffer.toString();
  }

  /// Generates CSV report for actionable low-attendance intervention
