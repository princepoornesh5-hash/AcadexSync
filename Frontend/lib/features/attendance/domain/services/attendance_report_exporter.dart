  /// Generates CSV report for department comparison and overview
  static String generateDepartmentAttendanceCsv({
    required String departmentId,
    required List<SectionAttendanceAnalytics> sections,
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();

    final totalStudents = sections.fold<int>(0, (sum, s) => sum + s.totalStudents);
    final totalSessions = sections.fold<int>(0, (sum, s) => sum + s.totalSessions);
    final totalLow = sections.fold<int>(0, (sum, s) => sum + s.lowAttendanceStudentCount);
    final avgAttendance = sections.isNotEmpty
        ? sections.fold<double>(0, (sum, s) => sum + s.attendancePercentage) / sections.length
        : 0.0;

    buffer.writeln(formatRow(['ACADEX DEPARTMENT ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['Department ID', departmentId]));
    buffer.writeln(formatRow(['Total Sections', sections.length]));
    buffer.writeln(formatRow(['Total Students', totalStudents]));
    buffer.writeln(formatRow(['Total Sessions Conducted', totalSessions]));
    buffer.writeln(formatRow(['Average Department Attendance', '${avgAttendance.toStringAsFixed(1)}%']));
    buffer.writeln(formatRow(['Total Students in Shortage', totalLow]));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Section Name',
      'Total Students',
      'Sessions Conducted',
      'Average Attendance %',
      'Students Below 75%',
      'Risk Status',
    ]));

    if (sections.isEmpty) {
      buffer.writeln(formatRow(['No sections found in department', '', '', '', '', '']));
    } else {
      for (final sec in sections) {
        buffer.writeln(formatRow([
          sec.sectionName.isNotEmpty ? sec.sectionName : sec.sectionId,
          sec.totalStudents,
          sec.totalSessions,
          '${sec.attendancePercentage.toStringAsFixed(1)}%',
          sec.lowAttendanceStudentCount,
          sec.attendancePercentage < 70 ? 'CRITICAL' : (sec.attendancePercentage < 75 ? 'WARNING' : 'GOOD'),
        ]));
      }
    }

    return buffer.toString();
  }

  /// Generates CSV report for college overview
  static String generateCollegeAttendanceCsv({
    required String collegeId,
    required List<DepartmentAttendanceComparison> departments,
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();

    final avgAttendance = departments.isNotEmpty
        ? departments.fold<double>(0, (sum, d) => sum + d.attendancePercentage) / departments.length
        : 0.0;

    buffer.writeln(formatRow(['ACADEX COLLEGE ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['College ID', collegeId]));
    buffer.writeln(formatRow(['Total Departments', departments.length]));
    buffer.writeln(formatRow(['Overall College Attendance', '${avgAttendance.toStringAsFixed(1)}%']));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Department Name',
      'Attendance %',
      'Student Count',
      'Faculty Count',
    ]));

    if (departments.isEmpty) {
      buffer.writeln(formatRow(['No departments found in college', '', '', '']));
    } else {
      for (final dept in departments) {
        buffer.writeln(formatRow([
          dept.departmentName,
          '${dept.attendancePercentage.toStringAsFixed(1)}%',
          dept.studentCount,
          dept.facultyCount,
        ]));
      }
    }

    return buffer.toString();
  }

  /// Generates CSV report for attendance sessions
  static String generateAttendanceSessionsCsv({
    required List<AttendanceSession> sessions,
    String scopeTitle = 'Attendance Sessions Export',
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();

    buffer.writeln(formatRow(['ACADEX ATTENDANCE SESSIONS LOG']));
    buffer.writeln(formatRow(['Scope', scopeTitle]));
    buffer.writeln(formatRow(['Total Sessions', sessions.length]));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Session ID',
      'Date',
      'Time Slot',
      'Subject',
      'Section',
      'Faculty ID',
      'Total Students',
      'Present',
      'Absent',
      'Late',
      'Excused',
      'Attendance %',
      'Submitted',
      'Locked',
      'Version',
      'Last Modified By',
    ]));

    if (sessions.isEmpty) {
      buffer.writeln(formatRow(['No attendance sessions found', '', '', '', '', '', '', '', '', '', '', '', '', '', '', '']));
    } else {
      for (final s in sessions) {
        buffer.writeln(formatRow([
          s.id,
          s.date.toIso8601String().split('T').first,
          s.timeSlot,
          s.subjectName.isNotEmpty ? s.subjectName : s.subjectId,
          s.sectionName.isNotEmpty ? s.sectionName : s.sectionId,
          s.facultyId,
          s.totalStudents,
          s.presentCount,
          s.absentCount,
          s.lateCount,
          s.excusedCount,
          '${s.attendancePercentage.toStringAsFixed(1)}%',
          s.isSubmitted ? 'YES' : 'NO',
          s.isLocked ? 'YES' : 'NO',
          'v${s.version}',
          s.lastModifiedBy ?? (s.createdBy ?? '-'),
        ]));
      }
    }

    return buffer.toString();
  }

  /// Generates a structured PDF/document-formatted text report
  static String generateStructuredPdfReport({
    required AttendanceReportResult reportResult,
  }) {
    final buffer = StringBuffer();
    const divider = '══════════════════════════════════════════════════════════════════════════';
    const subDivider = '──────────────────────────────────────────────────────────────────────────';

    buffer.writeln(divider);
    buffer.writeln('                      ACADEX CAMPUS MANAGEMENT SYSTEM                     ');
    buffer.writeln('                     OFFICIAL ATTENDANCE RECORD REPORT                    ');
    buffer.writeln(divider);
    buffer.writeln();

    buffer.writeln('Report Title  : ${reportResult.title}');
    buffer.writeln('Scope         : ${reportResult.scopeDescription}');
    buffer.writeln('Generated At  : ${reportResult.generatedAt.toIso8601String()}');
    buffer.writeln('Generated By  : ${reportResult.generatedBy}');
    if (reportResult.dateRange != null) {
      buffer.writeln('Period        : ${formatDateRange(reportResult.dateRange)}');
    }
    buffer.writeln('Total Records : ${reportResult.totalRecords}');
    buffer.writeln();

    if (reportResult.summaryStatistics.isNotEmpty) {
      buffer.writeln(subDivider);
      buffer.writeln('                        EXECUTIVE SUMMARY METRICS                         ');
      buffer.writeln(subDivider);
      for (final entry in reportResult.summaryStatistics.entries) {
        final keyPadded = entry.key.padRight(35);
        buffer.writeln('  $keyPadded : ${entry.value}');
      }
      buffer.writeln();
    }

    buffer.writeln(subDivider);
    buffer.writeln('                           DETAILED DATA TABLE                            ');
    buffer.writeln(subDivider);

    // Formatted Table Header
    buffer.writeln(reportResult.headers.map((h) => h.padRight(16)).join(' | '));
    buffer.writeln(subDivider);

    // Formatted Table Rows
    if (reportResult.rows.isEmpty) {
      buffer.writeln('                      -- No matching records found --                     ');
    } else {
      for (final row in reportResult.rows) {
        buffer.writeln(row.map((cell) => cell.toString().padRight(16)).join(' | '));
      }
    }

    buffer.writeln(subDivider);
    buffer.writeln();
    buffer.writeln('Institutional Notice: This document is an official electronic record generated');
    buffer.writeln('by the Acadex Attendance Subsystem. Compliance Threshold = 75.0%.');
    buffer.writeln(divider);

    return buffer.toString();
  }
