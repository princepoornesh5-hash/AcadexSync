    buffer.writeln(formatRow(['ACADEX LOW ATTENDANCE INTERVENTION REPORT']));
    buffer.writeln(formatRow(['Scope', scopeTitle]));
    buffer.writeln(formatRow(['Threshold', '${AttendanceAnalyticsConstants.lowAttendanceThreshold}%']));
    buffer.writeln(formatRow(['Students in Shortage', lowAttendanceStudents.length]));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Priority',
      'Student Name',
      'Roll Number',
      'Section',
      'Current Attendance %',
      'Sessions Present',
      'Sessions Absent',
      'Consecutive Classes Needed for 75%',
      'Status',
    ]));

    if (lowAttendanceStudents.isEmpty) {
      buffer.writeln(formatRow(['No students in critical shortage', '', '', '', '', '', '', '', '']));
    } else {
      final sorted = List<StudentAttendanceAnalytics>.from(lowAttendanceStudents)
        ..sort((a, b) => a.attendancePercentage.compareTo(b.attendancePercentage));

      for (int i = 0; i < sorted.length; i++) {
        final s = sorted[i];
        buffer.writeln(formatRow([
          i + 1,
          s.studentName.isNotEmpty ? s.studentName : s.studentId,
          s.rollNumber,
