    }

    return buffer.toString();
  }

  /// Generates CSV report for subject analytics
  static String generateSubjectAttendanceCsv({
    required SubjectAttendanceAnalytics subject,
    AttendanceDateRange? dateRange,
  }) {
    final buffer = StringBuffer();

    buffer.writeln(formatRow(['ACADEX SUBJECT ATTENDANCE REPORT']));
    buffer.writeln(formatRow(['Subject Name', subject.subjectName.isNotEmpty ? subject.subjectName : subject.subjectId]));
    buffer.writeln(formatRow(['Subject Code', subject.subjectId]));
    buffer.writeln(formatRow(['Overall Attendance', '${subject.attendancePercentage.toStringAsFixed(1)}%']));
    buffer.writeln(formatRow(['Total Sessions', subject.totalSessions]));
    buffer.writeln(formatRow(['Total Student Records', subject.totalStudentRecords]));
    buffer.writeln(formatRow(['Risk Standing', subject.riskLevel.name.toUpperCase()]));
    if (dateRange != null) {
      buffer.writeln(formatRow(['Date Range', formatDateRange(dateRange)]));
    }
    buffer.writeln();

    buffer.writeln(formatRow([
      'Metric',
      'Value',
      'Share %',
    ]));

    final total = subject.totalStudentRecords;
    final presentShare = total > 0 ? (subject.presentCount / total * 100).toStringAsFixed(1) : '0';
    final absentShare = total > 0 ? (subject.absentCount / total * 100).toStringAsFixed(1) : '0';
    final lateShare = total > 0 ? (subject.lateCount / total * 100).toStringAsFixed(1) : '0';
    final excusedShare = total > 0 ? (subject.excusedCount / total * 100).toStringAsFixed(1) : '0';

    buffer.writeln(formatRow(['Present', subject.presentCount, '$presentShare%']));
    buffer.writeln(formatRow(['Absent', subject.absentCount, '$absentShare%']));
    buffer.writeln(formatRow(['Late', subject.lateCount, '$lateShare%']));
    buffer.writeln(formatRow(['Excused', subject.excusedCount, '$excusedShare%']));

    return buffer.toString();
  }

